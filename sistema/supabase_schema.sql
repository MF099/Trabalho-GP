-- Schema Supabase para Sala de Guerra · Grupo 3 (Maré Seguros)
-- Execute este script no SQL Editor do projeto Supabase para habilitar persistência em nuvem multiusuário.

create table if not exists public.war_room_state (
  id text primary key,
  grupo text not null default 'G3 - Maré Seguros',
  status_date text not null default '2026-10-30',
  payload jsonb not null,
  updated_by text not null default 'Sistema',
  updated_at timestamptz not null default now()
);

create table if not exists public.war_room_lancamentos (
  id bigint generated by default as identity primary key,
  tipo_lancamento text not null,
  registrado_por text not null,
  resumo text not null,
  dados jsonb not null,
  created_at timestamptz not null default now()
);

-- Habilita RLS com acesso de leitura/escrita para o projeto acadêmico via chave publishable/anon
alter table public.war_room_state enable row level security;
alter table public.war_room_lancamentos enable row level security;

drop policy if exists "war_room_state_all" on public.war_room_state;
create policy "war_room_state_all"
  on public.war_room_state
  for all
  using (true)
  with check (true);

drop policy if exists "war_room_lancamentos_all" on public.war_room_lancamentos;
create policy "war_room_lancamentos_all"
  on public.war_room_lancamentos
  for all
  using (true)
  with check (true);
